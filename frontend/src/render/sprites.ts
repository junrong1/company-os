  '#': '#1c2938', // 鸽蓝 — the outline that holds a shape together
  k: '#3a4557', // 鸽蓝, lifted — a softer edge and a contact line
  o: '#475164', // 鲸鱼灰 — structure and frames
  w: '#8a5a34', // 土色 — timber
  W: '#a8703f', // 土色, lit — a timber surface catching the light
  v: '#63421f', // 土色, deep — timber in shadow, and legs
  g: '#b8c8d6', // 远天蓝, shaded — moulded plastic and metal
  G: '#dfeaef', // 远天蓝 — the lit side of the same
  d: '#7d8f9e', // 星蓝, deepened — a darker fitting
  n: '#f7fbf9', // 月白, lifted — paper and screens
  N: '#fffef8', // 象牙白 — the brightest highlight there is
  b: '#2376b7', // 花青 — a screen, a spine, a cushion
  B: '#7aa7c8', // 星蓝 — the lit side of the same
  e: '#189c7b', // 竹绿 — foliage
  E: '#83cbac', // 粉绿 — foliage in the light
  r: '#aa6a4c', // 火泥棕 — terracotta and clay
  R: '#c98662', // 火泥棕, lit
  f: '#74759b', // 落电紫 — upholstery
