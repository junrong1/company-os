/**
 * Pixel art: the props the office is furnished with, as ASCII grids.
 *
 * The grids stay ASCII rather than becoming PNGs, and the cast does the opposite. The reason
 * is review, not consistency: one prop is 1,024 glyphs, which is a diff a person can read,
 * while the cast at 48×64 across a rig and three feature libraries is closer to a quarter of a
 * million, at which point a grid file stops being a review artifact and becomes a binary in
 * disguise. So furniture is authored here and people are authored in `cast/`.
 *
 * Redrawn at 32 for the daylight office. The 16×16 originals were a dark-room set — the whole
 * `ART` palette was chosen to sit against ink — and doubling them would have doubled the
 * pixels without adding any: at 32 a desk can have a monitor that reads as a monitor and a
 * plant can have leaves you can count.
 *
 * Grid contract, asserted by the tests:
 *   PROPS   32 rows x 32 columns, glyphs from ART plus '.'
 */

/**
 * Glyph to colour, for props. '.' is transparent and is not a key here.
 *
 * Two of these are deliberately the darkest values in the office. `#` and `k` are the
 * dove-blue family the art direction reserves for readable separation — an outline's job is
 * to hold a shape apart from what is behind it, and on a daylight floor that takes the
 * darkest value available rather than the lightest. Everything else is daylight.
 */
